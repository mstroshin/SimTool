#!/usr/bin/env swift
import Foundation

// Regenerates the viewer literals that ship inside the binary from the files
// people edit:
//
//   web/<path>  →  Tool/Sources/SimToolWeb/WebViewerAssets.swift
//
// The viewer stays one binary with nothing to install beside it, while its
// HTML, CSS and JS live as real files with real editors. WebViewerAssetsTests
// fails when the literals fall behind the files. Run this after editing
// anything under web/, from the repository root:
//
//   swift Scripts/sync-web-viewer.swift

let indent = String(repeating: " ", count: 8)

// "js/network.js" → "jsNetworkJs": one property per file.
func identifier(_ path: String) -> String {
    let parts = path.split(whereSeparator: { !$0.isLetter && !$0.isNumber }).map(String.init)
    return (parts.first ?? "") + parts.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
}

let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
let webRoot = root.appendingPathComponent("web", isDirectory: true)
let destination = root.appendingPathComponent("Tool/Sources/SimToolWeb/WebViewerAssets.swift")

guard let enumerator = FileManager.default.enumerator(at: webRoot, includingPropertiesForKeys: [.isRegularFileKey], options: [.skipsHiddenFiles]) else {
    FileHandle.standardError.write(Data("No web/ directory here. Run this from the repository root.\n".utf8))
    exit(1)
}

var files: [(path: String, contents: String)] = []
for case let url as URL in enumerator where (try? url.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile) == true {
    let path = String(url.standardizedFileURL.path.dropFirst(webRoot.standardizedFileURL.path.count + 1))
    guard var contents = try? String(contentsOf: url, encoding: .utf8) else {
        FileHandle.standardError.write(Data("web/\(path) is not UTF-8 text.\n".utf8))
        exit(1)
    }
    // The raw literal's own delimiter and interpolation cannot appear inside
    // it, and quietly producing a file that does not compile is worse than stopping.
    for forbidden in ["\"\"\"#", "\\#("] where contents.contains(forbidden) {
        FileHandle.standardError.write(Data("web/\(path) contains \(forbidden), which would end or interpolate the literal.\n".utf8))
        exit(1)
    }
    // Editors end files with a newline; the page does not want it.
    if contents.hasSuffix("\n") { contents.removeLast() }
    files.append((path, contents))
}
files.sort { $0.path < $1.path }

var source = """
    // Generated by Scripts/sync-web-viewer.swift from web/ — do not edit.
    // The files under web/ are the copies to change; regenerate this after
    // editing them. WebViewerAssetsTests fails when the two disagree.

    enum WebViewerAssets {
        /// `web/<path>` → that file's contents, without its final newline.
        static let files: [String: String] = [

    """
for file in files {
    source += "        \"\(file.path)\": \(identifier(file.path)),\n"
}
source += "    ]\n"
for file in files {
    // Every line indented to the closing delimiter's column, which Swift then
    // strips: that is what makes the literal equal the file byte for byte.
    let body = file.contents
        .split(separator: "\n", omittingEmptySubsequences: false)
        .map { $0.isEmpty ? "" : indent + $0 }
        .joined(separator: "\n")
    source += "\n    static let \(identifier(file.path)) = #\"\"\"\n\(body)\n\(indent)\"\"\"#\n"
}
source += "}\n"

try Data(source.utf8).write(to: destination, options: [.atomic])
for file in files {
    print("web/\(file.path) (\(file.contents.count) chars)")
}
print("→ \(destination.path.dropFirst(root.path.count + 1))")
